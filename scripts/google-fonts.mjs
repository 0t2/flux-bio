// Generates src/shared/googleFonts.ts, the Google Fonts families the dashboard
// can search and pages can use, from the metadata in google-font-metadata
// (MIT), which mirrors the Google Fonts API without needing an API key.
//
//   npm pack google-font-metadata@6.0.8 && tar xzf google-font-metadata-6.0.8.tgz
//   node scripts/google-fonts.mjs package/data
//
// Only what FluxBio needs is kept: the name, the category, which of the page
// languages' scripts the family covers, its upright weights, and whether its
// weight is a variable axis (then one file covers every weight).

import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const dir = process.argv[2]
if (!dir) throw new Error('usage: node scripts/google-fonts.mjs <google-font-metadata>/data')
const families = JSON.parse(readFileSync(join(dir, 'google-fonts-v2.json'), 'utf8'))
const variable = JSON.parse(readFileSync(join(dir, 'variable.json'), 'utf8'))
const { version } = JSON.parse(readFileSync(join(dir, '..', 'package.json'), 'utf8'))

/** Letters for the scripts of FluxBio's page languages; keep in sync with SCRIPT_CODES in src/shared/fonts.ts. */
const SCRIPTS = {
	latin: 'l',
	vietnamese: 'v',
	thai: 't',
	'chinese-traditional': 'T',
	'chinese-hongkong': 'T',
	'chinese-simplified': 'S',
	japanese: 'j',
	korean: 'k',
	arabic: 'a',
}
const CATEGORIES = { 'sans-serif': 's', serif: 'r', display: 'd', handwriting: 'h', monospace: 'm' }

const lines = []
for (const font of Object.values(families)) {
	if (!/^[A-Za-z0-9 ]+$/.test(font.family)) throw new Error(`unexpected family name: ${font.family}`)
	const category = CATEGORIES[font.category]
	const scripts = [...new Set(font.subsets.map((subset) => SCRIPTS[subset]).filter(Boolean))].sort().join('')
	const weights = font.weights.filter((weight) => weight % 100 === 0 && weight >= 100 && weight <= 900)
	// Icon fonts, italic-only families and families for scripts no page language uses are left out.
	if (!category || !scripts || !weights.length || !font.styles.includes('normal')) continue
	const axis = variable[font.id]?.axes?.wght
	lines.push([font.family, category, scripts, weights.map((weight) => weight / 100).join(''), axis ? 'v' : ''].join('|'))
}
lines.sort((a, b) => a.localeCompare(b, 'en'))

writeFileSync(
	'src/shared/googleFonts.ts',
	`// Generated by scripts/google-fonts.mjs from google-font-metadata ${version} (MIT). Don't edit.
// One family per line: name|category|scripts|weights|variable (see src/shared/fonts.ts).
export const GOOGLE_FONTS = \`
${lines.join('\n')}
\`
`,
)
console.log(`${lines.length} families`)
