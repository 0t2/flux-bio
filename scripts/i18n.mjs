// Dashboard translations: `pnpm i18n check` lists what is missing or wrong;
// `pnpm i18n todo <language>` prints the keys that language still lacks, as JSON;
// `pnpm i18n server` writes src/shared/serverWords.ts, the few words the Worker needs from them.
import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs'
import { join, relative } from 'node:path'
import { runnerImport } from 'vite'

const root = new URL('..', import.meta.url).pathname
const { module: scan } = await runnerImport('./src/admin/i18n/scan.ts')

function files(dir, out = {}) {
	for (const name of readdirSync(dir)) {
		const path = join(dir, name)
		if (statSync(path).isDirectory()) files(path, out)
		else if (/\.(ts|tsx)$/.test(name) && !name.endsWith('.d.ts')) out[relative(root, path)] = readFileSync(path, 'utf8')
	}
	return out
}

const admin = files(join(root, 'src/admin'))
const all = { ...admin, ...files(join(root, 'src/shared')), ...files(join(root, 'src/templates')), ...files(join(root, 'src/worker')) }
const keys = scan.findKeys(all)
const localesDir = join(root, 'src/admin/i18n/locales')
const locales = readdirSync(localesDir).filter((name) => name.endsWith('.json'))
const [command = 'check', language] = process.argv.slice(2)

if (command === 'server') {
	const dictionary = (name) => JSON.parse(readFileSync(join(localesDir, `${name}.json`), 'utf8'))
	const { STARTER_IDS, starterContent } = (await runnerImport('./src/shared/starters.ts')).module
	const starterKeys = new Set()
	for (const id of STARTER_IDS) starterContent(id, '', (key) => (starterKeys.add(key), key))
	const server = { ...files(join(root, 'src/worker')), ...files(join(root, 'src/shared')) }
	const english = dictionary('en')
	const pick = (words, keys) => Object.fromEntries([...keys].sort().filter((key) => words[key]).map((key) => [key, words[key]]))
	const starters = Object.fromEntries(locales.map((name) => name.replace('.json', '')).sort().map((code) => [code, pick(dictionary(code), starterKeys)]))
	writeFileSync(
		join(root, 'src/shared/serverWords.ts'),
		`// Generated by \`pnpm i18n server\` from the dashboard's locale files. Don't edit.
import type { Locale } from './content'

/** What the API says, in English. */
export const ENGLISH: Record<string, string> = ${JSON.stringify(pick(english, scan.findKeys(server)), null, '\t')}

/** The text of the starters in each language. zh-TW needs none: its text is the key. */
export const STARTER_WORDS: Partial<Record<Locale, Record<string, string>>> = ${JSON.stringify(starters, null, '\t')}
`,
	)
	console.log('src/shared/serverWords.ts')
} else if (command === 'todo') {
	const words = JSON.parse(readFileSync(join(localesDir, `${language}.json`), 'utf8'))
	const { missing } = scan.checkLocale(keys, words)
	console.log(JSON.stringify(Object.fromEntries(missing.map((key) => [key, ''])), null, '\t'))
} else {
	let problems = 0
	const untranslated = scan.findUntranslated(Object.fromEntries(Object.entries(admin).filter(([path]) => !path.includes('/i18n/'))))
	if (untranslated.length) {
		problems += untranslated.length
		console.log(`Chinese text outside t()/msg() (${untranslated.length}):\n${untranslated.join('\n')}\n`)
	}
	for (const name of locales) {
		const result = scan.checkLocale(keys, JSON.parse(readFileSync(join(localesDir, name), 'utf8')))
		const count = result.missing.length + result.extra.length + result.broken.length
		problems += count
		console.log(`${name}: ${keys.size - result.missing.length}/${keys.size} translated` + (count ? `, missing ${result.missing.length}, extra ${result.extra.length}, placeholders wrong ${result.broken.length}` : ''))
		for (const key of result.broken) console.log(`  placeholders differ: ${key}`)
	}
	process.exit(problems ? 1 : 0)
}
